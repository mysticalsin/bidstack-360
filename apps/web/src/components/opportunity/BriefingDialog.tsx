// Brief drawer for "Ask Dust" actions. Calls
// POST /api/opportunities/:id/brief and renders the returned markdown.
// The endpoint is server-stubbed today; this UI stays valid when the
// backend swaps to a real Dust agent. Only `model` and `tokens` change.

import { useEffect } from 'react';
import { useTranslation } from 'react-i18next';

import { Button } from '@/components/ui/Button';
import { Dialog, DialogContent } from '@/components/ui/Dialog';
import { useOpportunityBrief } from '@/hooks/useOpportunityBrief';

import { briefReadPhase } from './brief-read';

function arrivedBrief(data: unknown): { brief: string; model: string; tokens: number } | null {
  if (!data || typeof data !== 'object') return null;
  const row = data as { brief?: unknown; model?: unknown; tokens?: unknown };
  if (typeof row.brief !== 'string') return null;
  return {
    brief: row.brief,
    model: typeof row.model === 'string' ? row.model : '',
    tokens: typeof row.tokens === 'number' ? row.tokens : 0,
  };
}

interface Props {
  opportunityId: string | undefined;
  opportunityLabel: string;
  open: boolean;
  onOpenChange: (open: boolean) => void;
}

export function BriefingDialog({ opportunityId, opportunityLabel, open, onOpenChange }: Props) {
  const { t } = useTranslation('crm');
  const brief = useOpportunityBrief(opportunityId);
  // A brief that has not arrived is not a blank dialog. Error wins over a stale brief.
  const phase = briefReadPhase({
    data: brief.data,
    isError: brief.isError,
    status: brief.status,
  });
  const arrived = phase === 'ready' ? arrivedBrief(brief.data) : null;

  // Auto-trigger generation on open, then drop the state when the dialog
  // closes so re-opening it always fetches fresh. Briefs are time-sensitive
  // and a 5-minute-old one is stale.
  useEffect(() => {
    if (open && opportunityId) brief.mutate();
    if (!open) brief.reset();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, opportunityId]);

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      {open ? (
        <DialogContent
          title={t('briefing.title', 'Brief: {{label}}', { label: opportunityLabel })}
          description={t(
            'briefing.description',
            'Executive summary generated by Dust (stubbed locally without DUST_API_KEY).',
          )}
        >
          {phase === 'unread' ? (
            <p
              role="status"
              data-testid="brief-generating"
              className="text-sm text-[var(--fg-secondary)]"
            >
              {t('briefing.unread', 'Checking the brief. It has not arrived.')}
            </p>
          ) : phase === 'failed' ? (
            <p role="alert" className="text-sm text-[var(--fg-secondary)]">
              {t('briefing.failed', 'Could not load the brief.')}
            </p>
          ) : arrived ? (
            <>
              <pre
                className="whitespace-pre-wrap rounded-md bg-[var(--surface-sunken)] p-4 text-xs text-[var(--fg-primary)] font-mono leading-relaxed"
                aria-label={t('briefing.contentAriaLabel', 'Brief content')}
              >
                {arrived.brief}
              </pre>
              <div className="mt-3 flex items-center justify-between text-[11px] text-[var(--fg-tertiary)]">
                <span>
                  {t('briefing.modelMeta', 'Model {{model}} · {{tokens}} tokens', {
                    model: arrived.model,
                    tokens: arrived.tokens,
                  })}
                </span>
                <div className="flex gap-2">
                  <Button
                    size="sm"
                    variant="secondary"
                    onClick={() => void navigator.clipboard.writeText(arrived.brief)}
                  >
                    {t('briefing.copy', 'Copy')}
                  </Button>
                  <Button size="sm" variant="secondary" onClick={() => brief.mutate()}>
                    {t('briefing.regenerate', 'Regenerate')}
                  </Button>
                </div>
              </div>
            </>
          ) : (
            <p className="text-sm text-[var(--fg-secondary)]">
              {t('briefing.empty', 'No brief text was returned.')}
            </p>
          )}
        </DialogContent>
      ) : null}
    </Dialog>
  );
}
